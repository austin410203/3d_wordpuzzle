export function talk(id, G) {
  const f = G.flags, has = (k) => G.has(k);
  if (id === 'amei') {
    if (!f.metAmei) {
      return [
        { do: () => { f.metAmei = 1; } },
        '哎呀,是小禾!長這麼高了,小時候你才到我膝蓋。現在到我肩膀。我縮水了,不算。',
        '你爺爺走的時候很安詳。他最後一句話是:「誰把我的假牙放進味噌湯?」',
        '……是我。我以為那是蘿蔔。',
        ['小禾', '……奶奶,我想要爺爺工具棚的鑰匙。'],
        '鑰匙在我這。不過——我家麻糬三天沒回家了。那隻胖貓最愛池塘東邊的草叢。',
        '幫我把牠找回來,我就把鑰匙給你。成交?',
        { do: () => { f.catQuest = 1; G.setGoal('cat'); } },
      ];
    }
    if (f.catQuest && !f.catHome) {
      if (G.catFollowing()) {
        return [
          '麻糬!你這個小沒良心的,三天跑去哪了!……啊,有魚的味道。誰餵的?',
          { do: () => G.catGoHome() },
          '謝謝你,小禾。這把是工具棚的鑰匙。',
          { do: () => { G.give('key'); G.setGoal('shed'); } },
          '你爺爺說,裡面有一雙「能推動整座山」的手套。他講話一向很誇張。上次他說他釣到一條跟船一樣大的魚。那條船是玩具船。',
        ];
      }
      return ['麻糬還沒回來嗎?那孩子只認吃的,跟你爺爺一樣。', '池塘東邊的草叢,記得喔。'];
    }
    return G.ameiShop();
  }
  if (id === 'wang') {
    if (!has('rod')) {
      const pre = f.catQuest ? ['貓要吃魚?那你來對地方了。'] : [];
      return [
        ...pre,
        '年輕人,會釣魚嗎?不會?很好,這池子裡的魚也不太會被釣。',
        '拿去,這是我第二好的釣竿。最好的那支被楓葉鯰拖走了,連同我的假牙。',
        { do: () => { G.give('rod'); if (f.catQuest && !f.catHome) G.setGoal('catch'); } },
        '面對水邊按 E 甩竿。浮標一沉,馬上按 E;然後等白線跑進綠色區域再按,連中三次就上鉤。',
        '池塘、瀑布下、山頂湖,各有不同的魚。全部釣齊的人,我會承認他是釣魚大師。目前名單:我。',
      ];
    }
    const n = Object.keys(G.state.fish).length;
    if (n >= 6 && !f.masterAngler) return [{ do: () => { f.masterAngler = 1; G.toast('稱號:釣魚大師', true); } }, '六種都釣到了?!……好吧。從今天起,名單上有兩個人了。', '我先寫我自己的名字,你在下面。字小一點。'];
    const lines = [
      `你已經釣到 ${n} 種魚了。我年輕的時候一天可以釣 ${n + 3} 種。池子裡明明只有三種。`,
      '楓葉鯰只在池塘深處出沒。要有耐心,還要有運氣,最好還要有我的假牙。',
      '聽說山頂湖有金鱗魚。我沒看過,但我很確定牠存在,因為我很想要。',
    ];
    return [lines[G.rand(lines.length)]];
  }
  if (id === 'cat') {
    if (f.catHome) return [['麻糬', '喵。(牠在曬太陽,完全不想理你。這就是貓。)']];
    if (G.catFollowing()) return [['麻糬', '喵~(牠蹭了蹭你的腳,一副「快走啦」的樣子。)']];
    if (!f.catQuest) return [['麻糬', '喵?(一隻胖胖的貓。牠看起來不打算跟陌生人回家。)']];
    if (G.fishCount() > 0) {
      return [['小禾', '麻糬,來,吃魚。'], { do: () => G.feedCat() }, ['麻糬', '喵嗚!(牠三口吃完,決定暫時把你當成好人。)'], ['小禾', '走吧,回家了。']];
    }
    return [['麻糬', '喵。(牠盯著你空空的手,露出鄙視的表情。)'], ['小禾', '……看來要用吃的收買牠。碼頭的王伯好像在釣魚。'], { do: () => { if (!has('rod')) G.setGoal('fish'); else G.setGoal('catch'); } }];
  }
  if (id === 'chen') {
    if (!f.metChen) {
      return [
        { do: () => { f.metChen = 1; } },
        '你……你是從溪那邊過來的?踩著石頭過來的?你沒看到鴨子嗎!',
        ['小禾', '鴨子?'],
        '溪邊有鴨子。三隻。牠們看人的眼神……很冷。',
        '我在這裡露營三個禮拜了。不是我怕鴨子,是鴨子怕我,我怕牠們害怕,所以我不過去。很合理。',
        '總之你開了一條石頭路,我欠你一次。這捆繩子送你——我本來要拿來綁鴨子的。',
        { do: () => { G.give('rope'); G.setGoal('ladder'); } },
        '營地後面山壁上那把舊梯子壞了,用繩子綁一綁就能爬上山腰。你爺爺以前每天爬,還邊爬邊唱歌。很難聽。',
      ];
    }
    const lines = [
      '你爺爺說過,樹要砍,也要種。我砍了三十年,種了三十一年。多出來那一年是因為鴨子把我的斧頭藏起來了。',
      '山腰的磨坊?阿松那小子人不錯,就是話很多。每句話都像論文。',
      '如果你要回村子,山腰西邊有一把小梯子可以直接下來,不過也壞了——你有繩子,對吧?',
      '別學鴨子叫。我是說真的。',
    ];
    return [lines[G.rand(lines.length)]];
  }
  if (id === 'song') {
    if (!f.millFixed) {
      if (!f.metSong) return [
        { do: () => { f.metSong = 1; G.setGoal('mill'); } },
        '你好,我是阿松。這座磨坊的……研究員。',
        '水車三年沒轉了。我寫了一篇論文叫《論水車為何不轉》,寫到第三百頁才發現,答案是「因為沒有水」。',
        '上面的引水槽有四道閘門,我這邊有四根拉桿。可是每根拉桿都不只動到一道門,我拉了三年,越拉越亂。',
        '你試試看?看清楚水流到哪裡被擋住、從哪裡漏掉。',
      ];
      return ['水從瀑布那邊進來,經過閘門一,然後分成兩條:一條往水車,一條往懸崖外——漏掉的那條就是我三年的青春。', '每根拉桿旁邊都有刻字,告訴你它會動到哪幾道門。'];
    }
    if (!has('lantern')) return [
      '轉了!它轉了!……我的論文要改名叫《論水車為何轉》。',
      '這盞提燈是你爺爺寄放在我這裡的。他說:「等有人讓水車轉起來,就把燈交給他。」',
      { do: () => { G.give('lantern'); G.setGoal('lift'); } },
      '水車有動力了,升降台也能用了。往北邊的懸崖走,搭上去就是三層。古燈林在三層的西邊。',
      '那邊的燈……據說要用對的順序點。至於什麼是對的順序,我寫了一篇論文,還沒寫完。',
    ];
    return [['阿松', '水車轉起來的聲音真好聽。比我的論文好聽。']];
  }
  if (id === 'yu') {
    if (!f.metYu) return [
      { do: () => { f.metYu = 1; } },
      '嗨!我叫小羽,我在挑戰這座山第三年了。目前最好成績:爬到這裡。',
      '前面的古燈林有四盞石燈,聽說點亮之後山壁會打開——可是我沒有火。我帶了三年的打火機,剛剛才發現是一支筆。',
      '對了,舊步道被倒木擋住了,從我們這一側應該踢得倒。踢倒以後就能直接下到山腰,不用搭升降台。',
      ...(G.state.postcards.p4 ? [] : ['雲海平台那間小屋裡好像有一張明信片,寫著奇怪的東西。']),
    ];
    if (f.rang) return ['你敲響了鐘?整座山都在回音!……那我也要上去!', '(她往完全相反的方向跑去。)'];
    if (f.doorOpen) return ['山壁真的打開了!……我一直以為那是一面很有個性的牆。'];
    return ['燈要照順序點。我猜是照名字筆畫?或是照我喜歡的程度?'];
  }
  return ['……'];
}

